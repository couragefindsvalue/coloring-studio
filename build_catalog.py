import os
import json

# Paths relative to the project root
ASSETS_DIR = os.path.join('public', 'assets')
OUTPUT_JS_PATH = os.path.join('src', 'catalog.js')

def generate_catalog():
    if not os.path.exists(ASSETS_DIR):
        print(f"❌ Error: Directory '{ASSETS_DIR}' does not exist.")
        return

    catalog_data = {}

    # Scan the assets directory for subfolders (categories)
    # Sort folders alphabetically
    categories = sorted([d for d in os.listdir(ASSETS_DIR) if os.path.isdir(os.path.join(ASSETS_DIR, d))])

    for category in categories:
        category_path = os.path.join(ASSETS_DIR, category)
        catalog_data[category] = []

        # Scan for all .svg files inside each category folder
        # Sort files alphabetically
        files = sorted([f for f in os.listdir(category_path) if f.endswith('.svg')])

        for file in files:
            # Convert filename like 'sports-car.svg' -> 'Sports Car'
            raw_name = os.path.splitext(file)[0]
            formatted_name = raw_name.replace('-', ' ').replace('_', ' ').title()

            # Use forward slashes and prepend /assets/ for the web URL path
            # Note: in Vite/React, anything in the 'public' folder is served from the root '/'
            rel_path = f"/assets/{category}/{file}"

            catalog_data[category].append({
                "name": formatted_name,
                "path": rel_path
            })

    # Convert Python dict to pretty-printed JSON string
    catalog_json = json.dumps(catalog_data, indent=2)

    # Construct the final JavaScript file content
    js_content = f"""// This file is auto-generated by build_catalog.py. Do not edit manually.
export const catalog = {catalog_json};

export const palette = [
  "#e63946", "#f4a261", "#f1c40f", "#2ecc71", "#3498db", "#9b59b6",
  "#fd79a8", "#8b5a2b", "#ffdbac", "#95a5a6", "#000000", "#ffffff"
];
"""

    # Ensure the src directory exists
    os.makedirs(os.path.dirname(OUTPUT_JS_PATH), exist_ok=True)

    # Write to the output file
    with open(OUTPUT_JS_PATH, 'w', encoding='utf-8') as f:
        f.write(js_content)

    print(f"✅ Successfully generated '{OUTPUT_JS_PATH}' with {len(catalog_data)} categories.")

if __name__ == '__main__':
    generate_catalog()